# Write a program to read two numbers and print their sum, difference, product and quotient.

num1 = int(input("Enter number 1 : "))
num2 = int(input("Enter number 2 : "))

sum = num1 + num2
print(f'The sum of the two numers {num1} and {num2} is {sum}')

diff = num1 - num2
print(f'The difference between the two numers {num1} and {num2} is {diff}')

prod = num1 * num2
print(f'The product of the two numers {num1} and {num2} is {prod}')

quot = num1 / num2 
print(f'The quotient of the two numers {num1} and {num2} is {quot}')

